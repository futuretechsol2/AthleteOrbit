export const skillKey = (program, level, event, skill) => `${program}|${level}|${event}|${skill}`;

export function skillsFor(program, level) {
  const byEvent = (SKILLS[program] || {})[level] || {};
  const out = [];
  for (const [event, list] of Object.entries(byEvent))
    for (const skill of list) out.push({ event, skill, key: skillKey(program, level, event, skill) });
  return out;
}

export function allAround(score) {
  const vals = EVENT_KEYS.map((k) => score[k]).filter((v) => v !== null && v !== undefined && v !== "" && !isNaN(Number(v)));
  if (!vals.length) return null;
  return Math.round(vals.reduce((a, b) => a + Number(b), 0) * 1000) / 1000;
}
export function eventsCompeted(score) {
  return EVENT_KEYS.filter((k) => score[k] !== null && score[k] !== undefined && score[k] !== "").length;
}
